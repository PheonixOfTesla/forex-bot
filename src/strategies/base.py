from __future__ import annotations

"""
Base Strategy Classes for Forex Trading Bot

Provides abstract base classes and data structures for trading strategies.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Dict, List, Optional, Any
import pandas as pd


class SignalDirection(Enum):
    """Direction of a trading signal."""
    LONG = "long"
    SHORT = "short"
    NEUTRAL = "neutral"


class SignalStrength(Enum):
    """Strength classification of a signal."""
    WEAK = "weak"
    MODERATE = "moderate"
    STRONG = "strong"


@dataclass
class Signal:
    """
    Trading signal generated by a strategy.

    Attributes:
        direction: Long, short, or neutral
        confidence: Confidence level (0.0 to 1.0)
        asset: The asset/pair this signal is for
        strategy_name: Name of the strategy that generated this signal
        timestamp: When the signal was generated
        strength: Signal strength classification
        reason: Human-readable explanation of the signal
        metadata: Additional strategy-specific data
    """
    direction: SignalDirection
    confidence: float
    asset: str
    strategy_name: str
    timestamp: datetime = field(default_factory=datetime.utcnow)
    strength: SignalStrength = SignalStrength.MODERATE
    reason: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        """Validate signal parameters."""
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError(f"Confidence must be between 0 and 1, got {self.confidence}")

    @property
    def is_actionable(self) -> bool:
        """Check if the signal is actionable (not neutral)."""
        return self.direction != SignalDirection.NEUTRAL


@dataclass
class TradeSetup:
    """
    Complete trade setup with entry, exit, and risk parameters.

    Attributes:
        signal: The signal this setup is based on
        entry_price: Planned entry price
        stop_loss: Stop loss price
        take_profit: Take profit price
        position_size: Suggested position size (in lots or units)
        risk_reward_ratio: Risk to reward ratio
        max_spread_pips: Maximum acceptable spread in pips
        valid_until: Expiration time for this setup
    """
    signal: Signal
    entry_price: float
    stop_loss: float
    take_profit: float
    position_size: float = 0.0
    risk_reward_ratio: float = 0.0
    max_spread_pips: float = 3.0
    valid_until: Optional[datetime] = None

    def __post_init__(self):
        """Calculate risk/reward ratio."""
        if self.signal.direction == SignalDirection.LONG:
            risk = abs(self.entry_price - self.stop_loss)
            reward = abs(self.take_profit - self.entry_price)
        else:
            risk = abs(self.stop_loss - self.entry_price)
            reward = abs(self.entry_price - self.take_profit)

        if risk > 0:
            self.risk_reward_ratio = reward / risk

    @property
    def risk_pips(self) -> float:
        """Calculate risk in pips (assuming 4 decimal places for forex)."""
        return abs(self.entry_price - self.stop_loss) * 10000

    @property
    def reward_pips(self) -> float:
        """Calculate reward in pips (assuming 4 decimal places for forex)."""
        return abs(self.take_profit - self.entry_price) * 10000


@dataclass
class StrategyStats:
    """
    Performance statistics for a strategy.

    Attributes:
        name: Strategy name
        total_signals: Total signals generated
        winning_trades: Number of winning trades
        losing_trades: Number of losing trades
        win_rate: Win rate percentage
        avg_profit_pips: Average profit in pips
        avg_loss_pips: Average loss in pips
        profit_factor: Profit factor (gross profit / gross loss)
        sharpe_ratio: Sharpe ratio
        max_drawdown: Maximum drawdown percentage
        is_enabled: Whether the strategy is currently enabled
        disabled_reason: Reason if disabled
        last_signal: Timestamp of last signal
    """
    name: str
    total_signals: int = 0
    winning_trades: int = 0
    losing_trades: int = 0
    win_rate: float = 0.0
    avg_profit_pips: float = 0.0
    avg_loss_pips: float = 0.0
    profit_factor: float = 0.0
    sharpe_ratio: float = 0.0
    max_drawdown: float = 0.0
    is_enabled: bool = True
    disabled_reason: str = ""
    last_signal: Optional[datetime] = None

    def update_win_rate(self):
        """Recalculate win rate."""
        total = self.winning_trades + self.losing_trades
        if total > 0:
            self.win_rate = self.winning_trades / total

    def update_profit_factor(self, total_profit: float, total_loss: float):
        """Update profit factor."""
        if total_loss > 0:
            self.profit_factor = total_profit / total_loss


class BaseStrategy(ABC):
    """
    Abstract base class for all trading strategies.

    All strategies must inherit from this class and implement
    the abstract methods.

    Attributes:
        name: Strategy identifier
        assets: List of assets this strategy trades
        min_confidence: Minimum confidence threshold for signals
        is_enabled: Whether the strategy is currently active
        stats: Performance statistics
    """

    name: str = "base_strategy"
    assets: List[str] = []
    min_confidence: float = 0.70

    def __init__(
        self,
        name: Optional[str] = None,
        assets: Optional[List[str]] = None,
        min_confidence: float = 0.70
    ):
        """
        Initialize the strategy.

        Args:
            name: Strategy name (defaults to class attribute)
            assets: List of assets to trade
            min_confidence: Minimum confidence for signals
        """
        if name:
            self.name = name
        if assets:
            self.assets = assets
        self.min_confidence = min_confidence
        self.is_enabled = True
        self.stats = StrategyStats(name=self.name)

    @abstractmethod
    def generate_signal(
        self,
        df: pd.DataFrame,
        features: Dict[str, Any]
    ) -> Optional[Signal]:
        """
        Generate a trading signal based on market data.

        Args:
            df: DataFrame with OHLCV data and indicators
            features: Dictionary of additional features/signals

        Returns:
            Signal object if conditions are met, None otherwise
        """
        pass

    @abstractmethod
    def calculate_entry_exit(
        self,
        signal: Signal,
        current_price: float,
        atr: float
    ) -> TradeSetup:
        """
        Calculate entry, stop loss, and take profit levels.

        Args:
            signal: The signal to create a setup for
            current_price: Current market price
            atr: Average True Range for volatility-based sizing

        Returns:
            TradeSetup with all trade parameters
        """
        pass

    def validate_setup(
        self,
        setup: TradeSetup,
        current_spread: float = 0.0
    ) -> bool:
        """
        Validate a trade setup meets minimum criteria.

        Checks:
        - Risk:Reward ratio >= 2:1
        - Spread is acceptable
        - Confidence meets threshold
        - Setup hasn't expired

        Args:
            setup: The trade setup to validate
            current_spread: Current spread in pips

        Returns:
            True if setup is valid, False otherwise
        """
        # Check R:R ratio (minimum 2:1)
        if setup.risk_reward_ratio < 2.0:
            return False

        # Check spread is acceptable
        if current_spread > setup.max_spread_pips:
            return False

        # Check confidence threshold
        if setup.signal.confidence < self.min_confidence:
            return False

        # Check expiration
        if setup.valid_until and datetime.utcnow() > setup.valid_until:
            return False

        return True

    def can_trade_asset(self, asset: str) -> bool:
        """
        Check if this strategy can trade a given asset.

        Args:
            asset: Asset symbol to check

        Returns:
            True if strategy trades this asset
        """
        # If no assets specified, trade all
        if not self.assets:
            return True
        return asset.upper() in [a.upper() for a in self.assets]

    def record_signal(self, signal: Signal):
        """
        Record a signal in the strategy statistics.

        Args:
            signal: Signal that was generated
        """
        self.stats.total_signals += 1
        self.stats.last_signal = signal.timestamp

    def record_trade_result(self, profit_pips: float):
        """
        Record a trade result in the strategy statistics.

        Args:
            profit_pips: Profit/loss in pips (negative for loss)
        """
        if profit_pips > 0:
            self.stats.winning_trades += 1
        else:
            self.stats.losing_trades += 1
        self.stats.update_win_rate()

    def disable(self, reason: str):
        """
        Disable the strategy.

        Args:
            reason: Reason for disabling
        """
        self.is_enabled = False
        self.stats.is_enabled = False
        self.stats.disabled_reason = reason

    def enable(self):
        """Enable the strategy."""
        self.is_enabled = True
        self.stats.is_enabled = True
        self.stats.disabled_reason = ""

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(name={self.name}, assets={self.assets})"
